import { describe, it } from 'mocha'
import { expect } from 'chai'

import { isDateFormatTemplate } from './isDateFormat.js'

describe('xlsx/isDateFormat', () => {
	it('should detect date format', () => {
		expect(isDateFormatTemplate('dd/mm/yyyy')).to.equal(true)
		expect(isDateFormatTemplate('dd/mm/yy;@')).to.equal(true)
		expect(isDateFormatTemplate('d/m/yyyy;@')).to.equal(true)
		expect(isDateFormatTemplate('d/m/yy;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-40c]yyyy-mm-dd')).to.equal(true)
		expect(isDateFormatTemplate('[$-419]d-mmm-yyyy;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-419]mmmm yyyy;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-419]d mmm;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-419]d mmm yy;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-419]d mmm yyyy;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-FC19]dd mmmm yyyy;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-FC19]dd\\ mmmm\\ yyyy\\ \\г\\.;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-FC19]dd mmmm yyyy г.;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-419]dddd d mmmm yyyy г.;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-804]aaaa;@')).to.equal(true)
		expect(isDateFormatTemplate('[$-en-US]yyyy-mm-dd')).to.equal(true)
		expect(isDateFormatTemplate('[<45000]"Due: "yyyy-mm-dd; "Date: "yyyy-mm-dd')).to.equal(true)
		expect(isDateFormatTemplate('[<40000]"Old";mm/dd/yyyy')).to.equal(true)
		expect(isDateFormatTemplate('[$-,F]yyyy-mm-dd')).to.equal(true)
		expect(isDateFormatTemplate('[$-fa-IR,300]yyyy-mm-dd')).to.equal(true)
		expect(isDateFormatTemplate('"Date: "yyyy-mm-dd')).to.equal(true)
		expect(isDateFormatTemplate('[hh]:mm:ss')).to.equal(true)
		expect(isDateFormatTemplate('[mm]:ss')).to.equal(true)
		expect(isDateFormatTemplate('[dd]')).to.equal(true)
		expect(isDateFormatTemplate('[d]:hh:mm')).to.equal(true)
		expect(isDateFormatTemplate('[hh]:mm:ss.000')).to.equal(true)
		expect(isDateFormatTemplate('[s].00')).to.equal(true) // Seconds elapsed in a minute. Forces seconds to display a leading zero if it's < 10.
		expect(isDateFormatTemplate('ss.00')).to.equal(true) // Excel forces a two-digit display for fractions of a second, padding with zeros if necessary.
		expect(isDateFormatTemplate('[m]:ss')).to.equal(true)
		expect(isDateFormatTemplate('d "days"')).to.equal(true)
		expect(isDateFormatTemplate('[>100]"Future: "d/m/yy;[<50]"Past: "d/m/yy;0 "Current: "d/m/yy')).to.equal(true)
		expect(isDateFormatTemplate('[DBNum1][$-404]yyyy"年"m"月"d"日";@')).to.equal(true)
		expect(isDateFormatTemplate('[Yellow][DBNum1][$-404]yyyy"年"m"月"d"日";@')).to.equal(true)
		expect(isDateFormatTemplate('m"月"d"日";@')).to.equal(true)
		expect(isDateFormatTemplate('"Date: " "Confirmed on " mm/dd/yyyy')).to.equal(true)
		expect(isDateFormatTemplate('[$-804][$-F800]yyyy-mm-dd')).to.equal(true)
	})

	it('should detect non-date format', () => {
		expect(isDateFormatTemplate('$#,##0.00')).to.equal(false)
		expect(isDateFormatTemplate('0.0 "days"')).to.equal(false)
		expect(isDateFormatTemplate('\\d "days"')).to.equal(false)
		expect(isDateFormatTemplate('"days"')).to.equal(false)
		expect(isDateFormatTemplate('0.0 \\m')).to.equal(false)
		expect(isDateFormatTemplate('0.0%')).to.equal(false)
		expect(isDateFormatTemplate('[>=100]0.0 पहुंचते "High"; 0.0')).to.equal(false)
		expect(isDateFormatTemplate('#,##0.00;(#,##0.00);""')).to.equal(false)
		expect(isDateFormatTemplate('[Red][>1000]0.00;[Blue][<0]0.00;0.00')).to.equal(false)
		expect(isDateFormatTemplate('[Green]0.0 "Units Up";[Red]-0.0 "Units Down";[Blue]"Zero change"')).to.equal(false)
		expect(isDateFormatTemplate('$#,##0.00;[Red]-$#,##0.00')).to.equal(false)
		expect(isDateFormatTemplate('\\y\\y\\y\\y-\\m\\m-\\d\\d')).to.equal(false)
	})
})